import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = {};
for (const file of readdirSync(resolve(root, 'contracts/errors')).filter((f) => f.endsWith('.json')).sort()) {
  const owner = file.slice(0, -5);
  for (const [code, entry] of Object.entries(JSON.parse(readFileSync(resolve(root, 'contracts/errors', file), 'utf8')))) {
    if (!/^[a-z][a-z0-9_]*$/.test(code) || catalog[code]) throw new Error('Invalid or duplicate error code: ' + code);
    if (!Number.isInteger(entry.status) || entry.status < 400 || entry.status > 599 || !entry.title?.trim() || entry.message_key !== 'error-' + owner + '-' + code.replaceAll('_', '-')) throw new Error('Invalid error metadata: ' + code);
    catalog[code] = { module: owner, ...entry };
  }
}
const encoded = JSON.stringify(catalog, null, 2);
const outputs = {
  'services/platform/internal/core/problems/catalog.generated.json': encoded + '\n',
  'apps/web/src/lib/i18n/errors.generated.ts': '// Generated by scripts/generate-errors.mjs. Do not edit.\nexport const errorCodes = ' + encoded + ' as const;\nexport type ErrorCode = keyof typeof errorCodes;\n',
};
for (const [file, content] of Object.entries(outputs)) {
  const path = resolve(root, file);
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8').replaceAll('\r\n','\n') !== content) throw new Error('Generated error catalog drift: ' + file);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
