import { test, expect } from '@playwright/test';
const fixture = JSON.parse(process.env.OCP_BROWSER_FIXTURE ?? '{}') as { merchant_id: string; merchant_token: string; provider_token: string };
test('merchant publishes, guest selects, provider suspends and restores', async ({ page, browser, request }) => {
  await page.goto('/merchant');
  await page.getByLabel('Merchant identifier').fill(fixture.merchant_id);
  await page.getByLabel('Temporary merchant credential').fill(fixture.merchant_token);
  await page.getByRole('button', { name: 'Connect merchant' }).click();
  await expect(page.getByText('You have no stores yet. Create your first store above.')).toBeVisible();
  await page.getByLabel('Store name').fill('Neighbourhood Kitchen');
  await page.getByRole('button', { name: 'Create store', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Neighbourhood Kitchen' })).toBeVisible();
  const workspace = page.url(); const store = new URL(workspace).pathname.split('/').at(-1)!;
  await page.goto('/merchant');
  await expect(page.getByRole('region', { name: 'Your stores' }).getByRole('link', { name: 'Neighbourhood Kitchen' })).toBeVisible();
  await expect(page.getByLabel('Store identifier', { exact: true })).toHaveCount(0);
  await page.getByLabel('Store name').fill('Second Kitchen');
  await page.getByRole('button', { name: 'Create store', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Second Kitchen' })).toBeVisible();
  await page.goto('/merchant');
  const managedStores = page.getByRole('region', { name: 'Your stores' });
  await expect(managedStores.getByRole('columnheader')).toHaveText(['Store name', 'Menu items', 'Draft revision', 'Last updated']);
  const storeRow = page.getByRole('row').filter({ has: page.getByRole('link', { name: 'Neighbourhood Kitchen', exact: true }) });
  await expect(storeRow.getByRole('cell').nth(0)).toHaveText('0');
  await expect(storeRow.getByRole('cell').nth(1)).toHaveText('No draft');
  await expect(storeRow.locator('time')).toHaveAttribute('datetime', /.+/);
  await expect(managedStores.getByRole('link')).toHaveCount(2);
  await expect(managedStores.getByRole('link', { name: 'Second Kitchen', exact: true })).toBeVisible();
  // Headers and values share their logical starting edge in both writing directions.
  for (const language of ['ar', 'en']) {
    await page.locator('.language-picker summary').click();
    await page.locator(`.language-picker button[value=${language}]`).click();
    const table = page.locator('.store-table table');
    await expect(table).toHaveCSS('direction', language === 'ar' ? 'rtl' : 'ltr');
    for (const cell of await table.locator('th, td').all()) {
      await expect(cell).toHaveCSS('text-align', 'start');
    }
  }
  await managedStores.getByRole('link', { name: 'Neighbourhood Kitchen', exact: true }).click();
  await expect(page).toHaveURL(workspace);
  const storefront = `/stores/${fixture.merchant_id}/${store}`;
  await page.getByRole('button', { name: 'Add menu item', exact: true }).click();
  await page.getByLabel('Item name', { exact: true }).fill('Döner');
  await page.getByLabel('Variant price in EUR', { exact: true }).fill('7');
  await page.getByRole('button', { name: 'Add choice group', exact: true }).click();
  await page.getByLabel('Choice group name').fill('Sauce');
  await page.getByLabel('Minimum choices').fill('1');
  await page.getByLabel('Option name', { exact: true }).fill('Garlic');
  await page.getByLabel('Extra price in EUR', { exact: true }).fill('0.5');
  await page.getByRole('button', { name: 'Add menu item', exact: true }).click();
  await page.getByLabel('Item name', { exact: true }).last().fill('Falafel');
  await page.getByRole('button', { name: 'Save private draft' }).click();
  await expect(page.getByRole('status')).toContainText('Draft saved');
  await page.goto('/merchant');
  await expect(storeRow.getByRole('cell').nth(0)).toHaveText('2');
  await expect(storeRow.getByRole('cell').nth(1)).toHaveText('1');
  await storeRow.getByRole('link').click();
  const guestContext = await browser.newContext(); const guest = await guestContext.newPage();
  await guest.goto('/');
  await expect(guest.getByRole('status')).toContainText('No stores are published yet.');
  await guest.goto(storefront); await expect(guest.getByText('This store has no public menu available.')).toBeVisible();
  await page.getByRole('button', { name: 'Publish saved draft' }).click();
  await expect(page.getByRole('status')).toHaveText('Menu published.');
  const noScriptContext = await browser.newContext({ javaScriptEnabled: false });
  const noScript = await noScriptContext.newPage();
  await noScript.goto('/');
  await noScript.getByLabel('Search by store name').fill('kitchen');
  await noScript.getByRole('button', { name: 'Search', exact: true }).click();
  await noScript.getByRole('region', { name: 'Published stores' }).getByRole('link', { name: 'Neighbourhood Kitchen', exact: true }).click();
  await expect(noScript.getByRole('heading', { name: 'Neighbourhood Kitchen', exact: true })).toBeVisible();
  await noScriptContext.close();
  await guest.goto('/');
  await expect(guest.getByRole('region', { name: 'Published stores' }).getByRole('link')).toHaveCount(1);
  await expect(guest.getByRole('link', { name: 'Second Kitchen', exact: true })).toHaveCount(0);
  await guest.getByLabel('Search by store name').fill('missing shop');
  await guest.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(guest.getByRole('status')).toContainText('No stores match this name.');
  await guest.getByLabel('Search by store name').fill('kitchen');
  await guest.getByRole('button', { name: 'Search', exact: true }).click();
  await guest.getByRole('region', { name: 'Published stores' }).getByRole('link', { name: 'Neighbourhood Kitchen', exact: true }).click();
  await expect(guest).toHaveURL(new RegExp(storefront + '$'));
  await guest.getByRole('button', { name: 'Check selection price' }).click();
  await expect(guest.getByRole('alert')).toContainText('Select available items');
  await guest.getByLabel('Garlic').check();
  await guest.getByLabel('Quantity', { exact: true }).fill('2');
  await guest.getByRole('button', { name: 'Check selection price' }).click();
  await expect(guest.getByRole('region', { name: 'Selection quote' })).toContainText('15.00');
  await expect(guest.getByRole('region', { name: 'Selection quote' })).toContainText('not an order');
  await guest.reload();
  await expect(guest.getByRole('region', { name: 'Selection quote' })).toContainText('Garlic');
  await guest.getByRole('button', { name: 'Place pickup order', exact: true }).click();
  await expect(guest.getByRole('heading', { name: 'Pickup order placed' })).toBeVisible();
  const receipt = guest.url();
  await expect(guest.getByRole('region', { name: 'Order details' })).toContainText('15.00');
  await expect(guest.getByRole('region', { name: 'Order details' })).toContainText('Sauce: Garlic');
  await expect(guest.getByText('Awaiting restaurant acceptance.', { exact: false })).toBeVisible();
  await guest.reload();
  await expect(guest).toHaveURL(receipt);
  // Language changes alter presentation, not agreed terms or guest authority.
  const tokenBeforeLanguageChange = (await guestContext.cookies()).find((cookie) => cookie.name.startsWith('ocp_guest_'))!.value;
  await guest.locator('.language-picker summary').click();
  await guest.locator('.language-picker button[value=ar]').click();
  await expect(guest).toHaveURL(receipt);
  await expect(guest.locator('html')).toHaveAttribute('dir','rtl');
  const arabicReceipt = guest.getByRole('region', { name: 'تفاصيل الطلب' });
  await expect(arabicReceipt).toContainText('Döner');
  await expect(arabicReceipt.locator('bdi').filter({hasText:/^Döner$/})).toHaveCSS('direction','ltr');
  expect((await guestContext.cookies()).find((cookie) => cookie.name.startsWith('ocp_guest_'))!.value).toBe(tokenBeforeLanguageChange);
  await guest.locator('.language-picker summary').click();
  await guest.locator('.language-picker button[value=en]').click();
  await expect(guest.getByRole('region', { name:'Order details' })).toContainText('15.00');
  await guest.goto(storefront);
  await guest.getByRole('button', { name: 'Place pickup order', exact: true }).click();
  await expect(guest).toHaveURL(receipt);
  const guestCookies = await guestContext.cookies();
  const credentialCookie = guestCookies.find((cookie) => cookie.name.startsWith('ocp_guest_'));
  expect(credentialCookie?.httpOnly).toBe(true);
  expect(credentialCookie?.sameSite).toBe('Strict');
  expect((await guest.content()).includes(credentialCookie!.value)).toBe(false);
  expect(await guest.evaluate(() => localStorage.length)).toBe(0);
  const unrelatedContext = await browser.newContext(); const unrelated = await unrelatedContext.newPage();
  await unrelated.goto(receipt);
  await expect(unrelated.getByText('Open this order in the browser used at checkout.', { exact: false })).toBeVisible();
  await expect(unrelated.getByRole('region', { name: 'Order details' })).toHaveCount(0);
  await unrelatedContext.close();
  // Merchant and customer operations use the same durable order through separate APIs.
  const orderId = new URL(receipt).pathname.split('/').at(-1)!;
  await page.getByRole('link', { name: 'Order inbox', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Pickup orders', exact: true })).toBeVisible();
  await page.getByRole('link', { name: orderId, exact: true }).click();
  await page.getByRole('button', { name: 'Accept order', exact: true }).click();
  await expect(page.getByText('Accepted by the restaurant.', { exact: false })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Accept order', exact: true })).toHaveCount(0);
  await guest.getByRole('link', { name: 'Refresh status', exact: true }).click();
  await expect(guest.getByText('Accepted by the restaurant.', { exact: false })).toBeVisible();
  await guest.getByRole('link', { name: 'Refresh status', exact: true }).click();
  await expect(guest.getByText('Accepted by the restaurant.', { exact: false })).toBeVisible();
  await guest.getByRole('button', { name: 'Cancel order', exact: true }).click();
  await expect(guest.getByText('This order is cancelled.', { exact: false })).toBeVisible();
  await expect(guest.getByRole('button', { name: 'Cancel order', exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: 'Refresh status', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Order details' })).toContainText('Cancelled');
  await page.getByRole('link', { name: 'Refresh status', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Order details' })).toContainText('Cancelled');
  await expect(page.getByRole('region', { name: 'Order details' }).getByRole('listitem')).toHaveCount(3);
  await page.goto(workspace);
  // Deletion is a draft edit, survives reload, and only reaches customers on publish.
  const removeItem = page.getByRole('button', { name: /Remove menu item.*Döner/ });
  const viewport = page.viewportSize();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(removeItem.locator('svg')).toHaveAttribute('aria-hidden', 'true');
  await removeItem.focus();
  await expect(page.getByRole('tooltip')).toHaveText(/Remove menu item.*Döner/);
  await page.keyboard.press('Escape');
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await removeItem.hover();
  await expect(page.getByRole('tooltip')).toHaveText(/Remove menu item.*Döner/);
  await page.getByRole('tooltip').hover();
  await expect(page.getByRole('tooltip')).toBeVisible();
  const tooltipBounds = await page.getByRole('tooltip').boundingBox();
  expect(tooltipBounds!.x).toBeGreaterThanOrEqual(0);
  expect(tooltipBounds!.x + tooltipBounds!.width).toBeLessThanOrEqual(390);
  await removeItem.click();
  if (viewport) await page.setViewportSize(viewport);
  await expect(page.getByLabel('Item name', { exact: true })).toHaveValue('Falafel');
  await page.getByRole('button', { name: 'Save private draft' }).click();
  await expect(page.getByRole('status')).toContainText('Draft saved');
  await page.reload();
  await expect(page.getByLabel('Item name', { exact: true })).toHaveValue('Falafel');
  await page.goto('/merchant');
  await expect(storeRow.getByRole('cell').nth(0)).toHaveText('1');
  await expect(storeRow.getByRole('cell').nth(1)).toHaveText('2');
  await storeRow.getByRole('link').click();
  await guest.goto(storefront);
  await expect(guest.getByRole('option', { name: 'Döner', exact: true })).toBeAttached();
  await page.getByRole('button', { name: 'Publish saved draft' }).click();
  await expect(page.getByRole('status')).toHaveText('Menu published.');
  await guest.goto(storefront);
  await expect(guest.getByRole('option', { name: 'Döner', exact: true })).toHaveCount(0);
  await expect(guest.getByRole('option', { name: 'Falafel', exact: true })).toBeAttached();
  // Private credentials are never serialized in rendered HTML or browser storage.
  expect((await page.content()).includes(fixture.merchant_token)).toBe(false);
  expect(await page.evaluate(() => localStorage.length)).toBe(0);
  const cookies = await page.context().cookies();
  expect(cookies.some((c) => c.name === 'ocp_merchant_session' && c.httpOnly && c.sameSite === 'Strict')).toBe(true);
  const adminContext = await browser.newContext(); const admin = await adminContext.newPage();
  await admin.goto('/admin'); await admin.getByLabel('Temporary provider credential').fill(fixture.provider_token);
  await admin.getByRole('button', { name: 'Connect provider' }).click();
  await admin.getByLabel("Order's merchant identifier").fill(fixture.merchant_id);
  await admin.getByLabel("Order's store identifier").fill(store);
  await admin.getByLabel('Order identifier', { exact: true }).fill(orderId);
  await admin.getByRole('button', { name: 'Inspect order', exact: true }).click();
  await expect(admin.getByRole('region', { name: 'Order details' })).toContainText('Cancelled');
  await expect(admin.getByRole('button', { name: 'Accept order', exact: true })).toHaveCount(0);
  await admin.getByLabel('Merchant identifier', { exact: true }).fill(fixture.merchant_id); await admin.getByLabel('Store identifier', { exact: true }).fill(store);
  await admin.getByRole('button', { name: 'Inspect publication' }).click();
  await admin.getByLabel('Reason for this action').fill('Browser moderation test');
  await admin.getByRole('button', { name: 'Suspend visibility' }).click();
  await expect(admin.getByRole('status')).toContainText('Public visibility suspended');
  await guest.goto('/');
  await expect(guest.getByRole('status')).toContainText('No stores are published yet.');
  await guest.goto(storefront); await expect(guest.getByText('This store has no public menu available.')).toBeVisible();
  await guest.goto(receipt); await expect(guest.getByRole('region', { name: 'Order details' })).toContainText('15.00');
  await admin.getByLabel('Reason for this action').fill('Browser review complete');
  await admin.getByRole('button', { name: 'Restore visibility' }).click();
  await expect(admin.getByRole('status')).toContainText('Visibility restored');
  await guest.goto(storefront); await expect(guest.getByRole('heading', { name: 'Neighbourhood Kitchen' })).toBeVisible();
  await guest.getByRole('button', { name: 'Check selection price' }).click();
  await guest.getByRole('button', { name: 'Place pickup order', exact: true }).click();
  const declinedReceipt = guest.url();
  const declinedId = new URL(declinedReceipt).pathname.split('/').at(-1)!;
  await page.goto(`${workspace}/orders/${declinedId}`);
  await page.getByRole('button', { name: 'Decline order', exact: true }).click();
  await guest.reload();
  await expect(guest.getByText('The restaurant declined this order.', { exact: false })).toBeVisible();
  await expect(guest.getByRole('button', { name: 'Cancel order', exact: true })).toHaveCount(0);
  expect((await admin.content()).includes(fixture.provider_token)).toBe(false);
  await guest.goto('/admin'); await expect(guest.getByLabel('Temporary provider credential')).toBeVisible();
  const csrf = await request.post('/merchant?/connect', { headers: { Origin: 'https://untrusted.example' }, form: { merchant: fixture.merchant_id, token: 'not-a-credential' } });
  expect(csrf.status()).toBe(403);
  await guestContext.close(); await adminContext.close();
});
