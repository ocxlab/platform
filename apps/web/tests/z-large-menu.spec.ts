import { reviewBasket } from './support/basket';
import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

const fixture = JSON.parse(process.env.OCP_BROWSER_FIXTURE ?? '{}') as {
  demo_merchant_id: string; demo_merchant_token: string; demo_menu: string;
};

test('48-product fixture loads for merchants and guests and prices a configured pizza', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = `http://browser-api:8080/api/v1/merchants/${fixture.demo_merchant_id}/stores`;
  const headers = () => ({ Authorization: `Bearer ${fixture.demo_merchant_token}`, 'Idempotency-Key': randomUUID() });
  const created = await request.post(base, { headers: headers(), data: { display_name: 'Large menu demo' } });
  expect(created.status()).toBe(201);
  const store = await created.json();
  const document = JSON.parse(fixture.demo_menu);
  document.items.find((item: { id: string }) => item.id === 'water').translations = { en: 'Water 0.5 l', de: 'Wasser 0,5 l', ar: 'ماء 0.5 لتر' };
  const saved = await request.put(`${base}/${store.id}/offering`, { headers: headers(), data: {
    base_revision: 0, model: { id: 'ocp.food.menu', version: '1.0.0' }, document,
  } });
  expect(saved.status()).toBe(201);
  const published = await request.put(`${base}/${store.id}/publication`, { headers: headers(), data: { expected_generation: 0, revision: 1 } });
  expect(published.status()).toBe(201);
  await page.goto('/merchant');
  await expect(page.locator('html')).toHaveAttribute('data-hydrated', 'true');
  await page.getByLabel('Merchant identifier', { exact: true }).fill(fixture.demo_merchant_id);
  await page.getByLabel('Temporary merchant credential').fill(fixture.demo_merchant_token);
  await page.getByRole('button', { name: 'Connect merchant' }).click();
  await expect(page.getByRole('row', { name: /Large menu demo/ })).toContainText('48');
  await page.getByRole('link', { name: 'Large menu demo', exact: true }).click();
  await expect(page.getByLabel('Item name', { exact: true })).toHaveCount(48);
  await expect(page.getByLabel('Category name', { exact: true })).toHaveCount(7);
  await page.getByLabel('Category name', { exact: true }).first().fill('Kitchen favourites');
  await page.getByRole('button', { name: 'Save private draft', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Draft saved');
  await page.getByRole('button', { name: 'Publish saved draft', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Menu published');
  await page.screenshot({ path: 'test-results/large-menu-merchant.png' });
  const storefront = await page.getByRole('link', { name: 'Open customer storefront', exact: true }).getAttribute('href');
  await page.getByRole('link', { name: 'Orders', exact: true }).click();
  await page.getByLabel('Accept new orders', { exact: true }).uncheck();
  await page.getByRole('combobox', { name: /^Acceptance of new orders/ }).selectOption('automatic');
  await page.getByRole('button', { name: 'Save ordering settings', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'New orders are paused' })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/ordering-controls-mobile.png', fullPage: true });
  await page.goto(storefront!);
  await expect(page.getByText('This restaurant has paused new orders.', { exact: false })).toBeVisible();
  await page.getByRole('link', { name: /Choose.*Pizza Margherita/ }).click();
  await expect(page.getByRole('button', { name: 'Add to basket', exact: true })).toBeDisabled();
  // Existing customer screens are advisory; the backend test separately checks
  // that quotes issued before a pause cannot bypass authoritative enforcement.
  const resumed = await request.put(`${base}/${store.id}/food/ordering`, {
    headers: headers(), data: { expected_revision: 1, accepting_orders: true, acceptance_mode: 'automatic' },
  });
  expect(resumed.status()).toBe(201);
  // SSE updates the open storefront, including an already-open customization.
  await expect(page.getByRole('button', { name: 'Add to basket', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Close customization', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-hydrated', 'true');
  await expect(page.locator('.card-grid .menu-card')).toHaveCount(48);
  await expect(page.getByRole('heading', { name: 'Kitchen favourites', exact: true })).toBeVisible();
  await page.locator('.category-picker summary').click();
  await expect(page.getByRole('group', { name: 'Categories', exact: true }).getByRole('checkbox')).toHaveCount(7);
  await page.getByRole('checkbox', { name: /Kitchen favourites/ }).check();
  await expect(page.locator('.menu-card')).toHaveCount(6);
  await page.getByRole('checkbox', { name: /^Pizza/ }).check();
  await expect(page.locator('.menu-card')).toHaveCount(18);
  await page.getByRole('button', { name: 'Close menu controls', exact: true }).click();
  const searchBox = await page.locator('.search-input').boundingBox();
  const resetButton = await page.getByRole('button', { name: 'Clear search and filters', exact: true }).boundingBox();
  expect(Math.abs(searchBox!.y - resetButton!.y)).toBeLessThan(1);
  expect(Math.abs(searchBox!.height - resetButton!.height)).toBeLessThan(1);
  await expect(page.locator('.search-feedback')).toContainText(/18.*dishes/);
  await expect(page.getByRole('group', { name: 'Selected categories' }).getByRole('button')).toHaveCount(2);
  await page.screenshot({ path: 'test-results/menu-filter-chips-mobile.png' });
  await page.getByRole('searchbox', { name: 'Search the menu', exact: true }).fill('doner');
  await expect(page.locator('.menu-card')).toHaveCount(5);
  await page.getByRole('button', { name: 'Clear search and filters', exact: true }).click();
  await expect(page.locator('.menu-card')).toHaveCount(48);
  // Floating controls use two separate rows on phones, and sticky search remains
  // reachable after scrolling instead of taking a second fixed bottom row.
  const tools = await page.locator('.floating-menu-tools').boundingBox();
  const basketControl = await page.locator('.floating-basket').boundingBox();
  expect(tools!.y + tools!.height).toBeLessThanOrEqual(basketControl!.y);
  await page.getByRole('link', { name: /Choose.*Pizza Margherita/ }).scrollIntoViewIfNeeded();
  const searchTop = await page.locator('.menu-toolbar').boundingBox();
  expect(searchTop!.y).toBeGreaterThanOrEqual(0);
  expect(searchTop!.y).toBeLessThan(2);
  await expect(page.locator('.menu-toolbar')).toHaveCSS('background-color', 'rgb(245, 247, 248)');
  await page.locator('.view-picker summary').focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('button', { name: 'List', exact: true })).toBeVisible();
  const viewTrigger = await page.locator('.view-picker summary').boundingBox();
  expect(viewTrigger!.width).toBe(44);
  expect(viewTrigger!.height).toBe(44);
  await expect(page.locator('.view-picker summary')).toHaveText('');
  await page.getByRole('button', { name: 'List', exact: true }).hover();
  await expect(page.getByRole('button', { name: 'List', exact: true })).toHaveCSS('background-color', 'rgb(206, 225, 234)');
  await page.screenshot({ path: 'test-results/menu-view-picker-mobile.png' });
  await page.keyboard.press('Escape');
  await expect(page.locator('.view-picker summary')).toBeFocused();
  await page.locator('.category-picker summary').click();
  const categoryPanel = await page.locator('.category-options').boundingBox();
  expect(categoryPanel!.x).toBeGreaterThanOrEqual(0);
  expect(categoryPanel!.x + categoryPanel!.width).toBeLessThanOrEqual(390);
  await page.screenshot({ path: 'test-results/menu-filters-mobile.png' });
  await page.getByRole('button', { name: 'Close menu controls', exact: true }).click();
  await page.setViewportSize({ width: 1280, height: 800 });
  const desktopTools = await page.locator('.floating-menu-tools').boundingBox();
  const desktopBasket = await page.locator('.floating-basket').boundingBox();
  expect(desktopTools!.x + desktopTools!.width).toBeLessThan(desktopBasket!.x);
  expect(Math.abs(desktopTools!.y - desktopBasket!.y)).toBeLessThan(2);
  await page.screenshot({ path: 'test-results/menu-controls-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('combobox', { name: /^Variant/ })).toHaveCount(0);
  await expect(page.getByRole('link', { name: /Choose.*Baklava/ })).toHaveAttribute('aria-disabled', 'true');
  const pizzaCard = page.getByRole('link', { name: /Choose.*Pizza Margherita/ });
  await pizzaCard.scrollIntoViewIfNeeded();
  const scrollPosition = await page.evaluate(() => scrollY);
  await pizzaCard.click();
  await expect(page.getByRole('dialog').getByRole('heading')).toBeFocused();
  expect(await page.evaluate(() => scrollY)).toBe(scrollPosition);
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(pizzaCard).toBeFocused();
  expect(await page.evaluate(() => scrollY)).toBe(scrollPosition);
  await page.locator('.language-picker summary').click();
  await page.locator('.language-picker button[value=ar]').click();
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl');
  const rtlTools = await page.locator('.floating-menu-tools').boundingBox();
  const rtlLanguage = await page.locator('.language-picker').boundingBox();
  const rtlBasket = await page.locator('.floating-basket').boundingBox();
  const rtlView = await page.locator('.view-picker summary').boundingBox();
  const rtlCategories = await page.locator('.category-picker summary').boundingBox();
  // Check mirrored control ordering without assuming which side reserves a scrollbar gutter.
  expect(rtlTools!.x).toBeGreaterThan(rtlLanguage!.x + rtlLanguage!.width);
  expect(rtlCategories!.x + rtlCategories!.width).toBeLessThan(rtlView!.x);
  expect(rtlLanguage!.x + rtlLanguage!.width).toBeLessThan(rtlBasket!.x);
  expect(rtlTools!.y + rtlTools!.height).toBeLessThanOrEqual(rtlBasket!.y);
  await expect(page.locator('.menu-card').first()).toHaveCSS('direction', 'rtl');
  await expect(page.getByRole('link', { name: /ماء 0.5 لتر/ })).toBeVisible();
  await page.locator('.category-picker summary').click();
  const rtlPanel = await page.locator('.category-options').boundingBox();
  expect(rtlPanel!.x).toBeGreaterThanOrEqual(0);
  expect(rtlPanel!.x + rtlPanel!.width).toBeLessThanOrEqual(390);
  await page.screenshot({ path: 'test-results/menu-filters-arabic-mobile.png' });
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 1280, height: 800 });
  const rtlDesktopTools = await page.locator('.floating-menu-tools').boundingBox();
  const rtlDesktopBasket = await page.locator('.floating-basket').boundingBox();
  expect(rtlDesktopBasket!.x + rtlDesktopBasket!.width).toBeLessThan(rtlDesktopTools!.x);
  await page.locator('.view-picker summary').click();
  const rtlViewPanel = await page.locator('.view-switch').boundingBox();
  expect(rtlViewPanel!.x + rtlViewPanel!.width).toBeLessThanOrEqual(1280);
  await page.screenshot({ path: 'test-results/menu-controls-arabic-desktop.png' });
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/menu-cards-arabic-mobile.png' });
  await page.locator('.language-picker summary').click();
  await page.locator('.language-picker button[value=en]').click();
  await expect(page.locator('html')).toHaveAttribute('dir', 'ltr');
  await expect(page.locator('html')).toHaveAttribute('data-hydrated', 'true');
  await page.getByLabel('Search the menu', { exact: true }).fill('pizza');
  await expect(page.locator('.menu-card')).toHaveCount(12);
  await page.getByLabel('Search the menu', { exact: true }).fill('');
  await page.locator('.view-picker summary').click();
  await page.getByRole('button', { name: 'List', exact: true }).click();
  await expect(page.locator('.menu-list .menu-card')).toHaveCount(48);
  await page.locator('.view-picker summary').click();
  await page.getByRole('button', { name: 'Dropdown', exact: true }).click();
  await page.setViewportSize({ width: 320, height: 640 });
  const compactTools = await page.locator('.floating-menu-tools').boundingBox();
  expect(compactTools!.x + compactTools!.width).toBeLessThanOrEqual(320);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 390, height: 844 });
  const items = page.getByRole('combobox', { name: 'Menu item', exact: true });
  await expect(items.locator('option')).toHaveCount(49);
  await expect(items.locator('option[value=baklava]')).toHaveJSProperty('disabled', true);
  await items.selectOption('pizza-margherita');
  await expect(page.getByRole('dialog').getByRole('heading', { name: 'Pizza Margherita' })).toBeFocused();
  await page.getByRole('combobox', { name: /^Variant/ }).selectOption('large');
  await page.getByLabel('Extra Käse', { exact: false }).check();
  await page.getByLabel('Knoblauch', { exact: false }).check();
  await page.getByText('Add a note for this dish', { exact: true }).click();
  await page.getByRole('textbox', { name: 'Add a note for this dish', exact: true }).fill('Please slice the pizza');
  await page.screenshot({ path: 'test-results/basket-customization-mobile.png' });
  await page.getByRole('button', { name: 'Add to basket', exact: true }).click();
  await reviewBasket(page);
  await expect(page.getByRole('complementary', { name: 'Your basket' })).toContainText('12.00');
  await page.getByRole('button', { name: 'Continue browsing', exact: true }).click();
  // A second dish remains a separate line; changing the basket invalidates the
  // previous review instead of leaving a stale checkout button available.
  await page.getByRole('combobox', { name: 'Menu item', exact: true }).selectOption('water');
  await page.getByRole('button', { name: 'Add to basket', exact: true }).click();
  await page.getByRole('button', { name: /Your basket/ }).click();
  const basket = page.getByRole('complementary', { name: 'Your basket' });
  const water = basket.getByRole('listitem').filter({ hasText: 'Water 0.5 l' });
  await water.getByRole('button', { name: 'Add note', exact: true }).click();
  const noteBox = await water.getByRole('textbox', { name: 'Add a note for this dish', exact: true }).boundingBox();
  const itemActions = await water.locator('.line-actions').boundingBox();
  expect(noteBox!.y - (itemActions!.y + itemActions!.height)).toBeGreaterThanOrEqual(12);
  await water.getByRole('button', { name: 'Add note', exact: true }).click();
  await water.getByRole('button', { name: 'Increase quantity', exact: true }).click();
  await water.getByRole('button', { name: 'Decrease quantity', exact: true }).click();
  await water.getByRole('button', { name: 'Remove selection', exact: true }).click();
  await expect(basket.getByRole('listitem')).toHaveCount(1);
  await page.getByRole('button', { name: 'Continue browsing', exact: true }).click();
  await page.getByRole('combobox', { name: 'Menu item', exact: true }).selectOption('water');
  await page.getByRole('button', { name: 'Add to basket', exact: true }).click();
  await page.getByRole('button', { name: /Your basket/ }).click();
  await water.getByRole('button', { name: 'Edit selection', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Quantity', exact: true }).fill('2');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await basket.getByText('Note for the whole order', { exact: true }).click();
  await basket.getByLabel('Note for the whole order', { exact: true }).fill('Please pack the drinks separately');
  await page.reload();
  await reviewBasket(page);
  await expect(basket.getByRole('listitem')).toHaveCount(2);
  await basket.locator('.order-note summary').click();
  await expect(basket.getByLabel('Note for the whole order', { exact: true })).toHaveValue('Please pack the drinks separately');
  await reviewBasket(page);
  await expect(basket).toContainText('16.00');
  // Publication changes keep the basket open and preserve customer choices.
  const latest = await request.get(`${base}/${store.id}/offering`, { headers: headers() });
  expect(latest.status()).toBe(200);
  const latestMenu = (await latest.json()).document;
  for (const available of [false, true]) {
    latestMenu.items.find((item: { id: string }) => item.id === 'water').available = available;
    const revision = available ? 3 : 2;
    const updated = await request.put(`${base}/${store.id}/offering`, { headers: headers(), data: {
      base_revision: revision, model: { id: 'ocp.food.menu', version: '1.0.0' }, document: latestMenu,
    } });
    expect(updated.status()).toBe(201);
    const publication = await request.put(`${base}/${store.id}/publication`, { headers: headers(), data: { expected_generation: revision, revision: revision + 1 } });
    expect(publication.status()).toBe(201);
    if (available) await expect(page.getByRole('button', { name: 'Place pickup order', exact: true })).toBeEnabled();
    else await expect(page.getByRole('button', { name: 'Place pickup order', exact: true })).toBeDisabled();
    await expect(basket.getByRole('listitem')).toHaveCount(2);
  }
  await page.setViewportSize({ width: 390, height: 600 });
  const headerBefore = await basket.locator('.basket-header').boundingBox();
  const footerBefore = await basket.locator('.basket-checkout').boundingBox();
  const scroll = basket.getByRole('region', { name: 'Items in your basket' });
  expect(await scroll.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true);
  await scroll.evaluate(element => element.scrollTop = element.scrollHeight);
  expect((await basket.locator('.basket-header').boundingBox())?.y).toBe(headerBefore?.y);
  expect((await basket.locator('.basket-checkout').boundingBox())?.y).toBe(footerBefore?.y);
  await page.screenshot({ path: 'test-results/basket-fixed-checkout-mobile.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/large-menu-customer-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Place pickup order', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Order details' })).toContainText('Pizza Margherita');
  await expect(page.getByRole('region', { name: 'Order details' })).toContainText('16.00');
  await expect(page.getByRole('region', { name: 'Order details' })).toContainText('Please slice the pizza');
  await expect(page.getByRole('region', { name: 'Order details' })).toContainText('Please pack the drinks separately');
  await expect(page.getByRole('region', { name: 'Order details' })).toContainText('Water 0.5 l');
  const receipt = new URL(page.url()).pathname;
  await page.goto(`${storefront!.replace('/stores/', '/merchant/stores/')}/orders`);
  await page.getByRole('link', { name: receipt.split('/').at(-1), exact: true }).click();
  await expect(page.getByRole('region', { name: 'Order details' })).toContainText('Please pack the drinks separately');
  expect(errors).toEqual([]);
});
